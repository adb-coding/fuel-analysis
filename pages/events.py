@callback(
    Output('events-df','data'),
    Output('type-dropdown','options'),
    Output('type-dropdown','value'),
    Input('events-tab','id')
)
def load_events_df(_):
    events_df = extract_events(country='IT')
    events_types = list(events_df['type'].unique())
    events_countries = list(events_df['country'].unique())

    return events_df.to_dict('records'), events_types, events_types


@callback(
    Output('event-plot','figure'),
    Output('event-table','children'),
    Input('events-df','data'),
    Input('type-dropdown','value'),
    Input('barchart-elements', 'value')
)
def event_plot(events_df, value, number):

    events = pd.DataFrame(events_df)

    if value:
        if isinstance(value, str):
            events = events[events['type'] == value]
        elif isinstance(value, list):
            events = events[events['type'].isin(value)]
    
    events = events.sort_values(by='pct_change', ascending=False).reset_index(drop=True)
    events['pct_change'] = round(events['pct_change'] * 100, 3)
    events_filtered = events.iloc[:number]
    events_filtered.sort_values(by='pct_change', ascending=False)

    fig = px.bar(
        events_filtered, x='id', y='pct_change',
        color='type',
        custom_data=['hover']
    )

    # fig.update_traces(hovertemplate='%{y}%<extra></extra>')
    fig.update_traces(hovertemplate="%{customdata[0]}<extra></extra>")
    fig.update_yaxes(title_text='% Change')
    fig.update_layout()

    # events_table = dbc.Table.from_dataframe(events.drop('hover', axis=1))
    events_table = dash_table.DataTable(
        events.drop('hover', axis=1).to_dict("records"), columns=[{"name": i, "id": i} for i in events.columns],
        page_size=10,
        style_table={"overflowX":"auto"}
    )
    return fig, events_table